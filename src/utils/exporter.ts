import type { Deck, Question } from '../types'
import { buildStudyGuide } from './quizGenerator'

function letter(i: number): string {
  return String.fromCharCode(65 + i)
}

export function buildMarkdown(deck: Deck, questions: Question[]): string {
  const guide = buildStudyGuide(deck)
  const out: string[] = []
  out.push(`# ${deck.name} — Reviewer`, '')
  out.push(`_Generated by TalaTest on ${new Date().toLocaleDateString()}_`, '')
  out.push('## Part 1: Study Guide', '')
  for (const s of guide.sections) {
    out.push(`### ${s.title}`, '')
    if (s.summary) out.push(s.summary, '')
    for (const t of s.takeaways) out.push(`- ${t}`)
    if (s.takeaways.length) out.push('')
    out.push(`_Source: ${s.citation}_`, '')
  }
  out.push('## Glossary', '')
  for (const c of guide.glossary) out.push(`- **${c.term}** — ${c.definition}`)
  out.push('')
  out.push('## Part 2: Practice Quiz', '')
  questions.forEach((q, i) => {
    out.push(`**${i + 1}.** ${q.type === 'truefalse' ? 'True or False: ' : ''}${q.prompt}`, '')
    if (q.type === 'mcq') q.options.forEach((o, k) => out.push(`   ${letter(k)}. ${o}`))
    else if (q.type === 'identification') out.push('   Answer: ______________________')
    else out.push('   ( ) True   ( ) False')
    out.push('')
  })
  out.push('---', '', '## Part 3: Answer Key', '')
  questions.forEach((q, i) => {
    const ans = q.type === 'mcq' ? `${letter(q.correctIndex)}. ${q.answer}` : q.answer
    out.push(`${i + 1}. **${ans}** — ${q.explanation} _(${q.citation})_`)
  })
  out.push('')
  return out.join('\n')
}

/** Plain-text variant: same content without Markdown syntax. */
export function buildText(deck: Deck, questions: Question[]): string {
  return buildMarkdown(deck, questions)
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/(^|\s)_(.+?)_(?=\s|$|[.,)])/g, '$1$2')
}

export function safeFileName(name: string): string {
  return (
    name
      .replace(/\.[^.]+$/, '')
      .replace(/[^\p{L}\p{N}]+/gu, '-')
      .replace(/^-+|-+$/g, '')
      .toLowerCase() || 'reviewer'
  )
}

export function downloadFile(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
